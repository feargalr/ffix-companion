/**
 * Validates game data: duplicate IDs, invalid references, missing fields and
 * inconsistent progression metadata. Run with `npm run validate`.
 * Pass --report to also write docs/content-status.md.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { ALL_AREAS } from '../src/data/index';
import { summarise, validateData } from '../src/lib/validate';

const issues = validateData(ALL_AREAS);
const errors = issues.filter((i) => i.level === 'error');
const warnings = issues.filter((i) => i.level === 'warning');
const summary = summarise(ALL_AREAS);

console.log(`Areas: ${summary.areas}  Entries: ${summary.entries}`);
console.log('Verification:', summary.byVerification);
console.log('Missability: ', summary.byMissability);
for (const w of warnings) console.warn(`WARN  ${w.where}: ${w.message}`);
for (const e of errors) console.error(`ERROR ${e.where}: ${e.message}`);

if (process.argv.includes('--report')) {
  const lines: string[] = [
    '# Content status (generated)',
    '',
    'Generated by `npm run report`. Do not edit by hand.',
    '',
    `- Areas: **${summary.areas}**`,
    `- Checklist entries: **${summary.entries}**`,
    `- Verification: ${Object.entries(summary.byVerification).map(([k, v]) => `${k} ${v}`).join(', ')}`,
    `- Missability: ${Object.entries(summary.byMissability).map(([k, v]) => `${k} ${v}`).join(', ')}`,
    '',
    '## Per area',
    '',
    '| # | Area | Entries | Single-source | Revisit unconfirmed |',
    '|---|------|--------:|--------------:|--------------------:|',
    ...ALL_AREAS.map(
      (a) =>
        `| ${a.order} | ${a.location} — ${a.visit} | ${a.entries.length} | ${
          a.entries.filter((e) => e.verification !== 'verified').length
        } | ${a.entries.filter((e) => e.missability === 'unconfirmed').length} |`,
    ),
    '',
    '## Entries not confirmed by two sources',
    '',
    ...ALL_AREAS.flatMap((a) =>
      a.entries
        .filter((e) => e.verification !== 'verified')
        .map((e) => `- \`${e.id}\` — ${e.name} (${e.verification}; sources: ${e.sources.join(', ')})`),
    ),
    '',
    '## Entries with caveats noting a source disagreement',
    '',
    ...ALL_AREAS.flatMap((a) =>
      a.entries
        .filter((e) => (e.caveats ?? []).some((c) => /disagree|lists this as|calls this|calls it|vs /i.test(c)))
        .map((e) => `- \`${e.id}\` — ${e.name}: ${(e.caveats ?? []).find((c) => /disagree|lists this as|calls this|calls it|vs /i.test(c))}`),
    ),
    '',
  ];
  mkdirSync('docs', { recursive: true });
  writeFileSync('docs/content-status.md', lines.join('\n'));
  console.log('Wrote docs/content-status.md');
}

if (errors.length) {
  console.error(`\n${errors.length} error(s).`);
  process.exit(1);
}
console.log(`\nData OK (${warnings.length} warning(s)).`);
